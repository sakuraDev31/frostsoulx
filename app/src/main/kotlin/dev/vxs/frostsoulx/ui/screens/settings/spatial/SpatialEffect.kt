enum class EffectCategory(val label: String) {
    ALL("All"),
    BASS("Bass"),
    SURROUND("Surround"),
    HIFI("Hi-fi"),
    CONCERT("Concert"),
    ROOMS("Rooms"),
}

enum class EffectSortOption(val label: String) {
    RECOMMENDED("Recommended"),
    ALPHABETICAL("A–Z"),
}

data class SpatialEffect(
    val id: String,
    val name: String,
    val description: String,
    val category: EffectCategory,
    @DrawableRes val iconRes: Int,
    val isNew: Boolean = false,
    val defaultControls: ImmersiveControls,
) {
    fun toControls(enabled: Boolean = true): ImmersiveControls =
        defaultControls.copy(enabled = enabled)
}

